"""Training pipeline:  CSV -> validate -> features -> split -> fit -> evaluate -> save.

Usage:  python -m training.train --data data/your_dataset.csv --output-dir models
"""
from __future__ import annotations

import argparse
import json
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split

from app.modeling import ALGORITHMS, ModelBundle, build_estimator
from preprocessing.dataset import load_dataset
from preprocessing.pipeline import build_feature_frame, median_baseline, to_model_input, trainable_columns
from training.evaluate import evaluate
from training.split import split_dataset

SYNTHETIC_WARNING = ("The dataset is SYNTHETIC (generated by training/generate_sample_data.py). These metrics only prove the pipeline runs; "
                     "they say NOTHING about real-world phishing detection performance.")


def fit_model(algorithm: str, X_train: pd.DataFrame, y_train: np.ndarray, seed: int):
    est, params = build_estimator(algorithm, seed)
    if algorithm == "xgboost":  # hold out 10% of the training split for early stopping (the test split is never touched)
        Xa, Xv, ya, yv = train_test_split(X_train, y_train, test_size=0.1, random_state=seed, stratify=y_train)
        est.fit(Xa, ya, eval_set=[(Xv, yv)], verbose=False)
        params["best_iteration"] = int(getattr(est, "best_iteration", est.n_estimators))
    else:
        est.fit(X_train, y_train)
        params["n_iter_"] = int(est.n_iter_)
    return est, params


def lib_versions() -> dict:
    import sklearn
    v = {"python": platform.python_version(), "numpy": np.__version__, "pandas": pd.__version__, "scikit_learn": sklearn.__version__}
    for mod in ("xgboost", "shap"):
        try:
            v[mod] = __import__(mod).__version__
        except Exception:
            v[mod] = None
    return v


def run(data: str, output_dir: str = "models", algorithm: str = "xgboost", test_size: float = 0.2, seed: int = 42,
        threshold: float = 0.5, group_by_domain: bool = True, verbose: bool = True) -> dict:
    log = print if verbose else (lambda *a, **k: None)
    df, report = load_dataset(data)
    log(f"Dataset: {report.rows_out} usable rows of {report.rows_in}  classes={report.class_counts}  "
        f"dropped(blank={report.dropped_blank_url}, invalid={report.dropped_invalid_url}, dup={report.dropped_duplicates}, conflicting={report.dropped_conflicting_labels})")
    if report.synthetic:
        log("WARNING: " + SYNTHETIC_WARNING)

    feats = build_feature_frame(df)
    y = df["label"].to_numpy()
    tr, te = split_dataset(df, test_size, seed, group_by_domain)
    names, dropped = trainable_columns(feats.iloc[tr])
    if dropped:
        log(f"Dropping {len(dropped)} feature(s) with no observed values in the training split: {dropped}")
    X_tr, X_te = to_model_input(feats.iloc[tr], names), to_model_input(feats.iloc[te], names)

    est, params = fit_model(algorithm, X_tr, y[tr], seed)
    bundle = ModelBundle(est, {})
    bundle.metadata = {"algorithm": algorithm, "feature_names": names}  # minimal, so predict_proba can reorder columns
    metrics = {"test": evaluate(y[te], bundle.predict_proba(X_te), threshold), "train": evaluate(y[tr], bundle.predict_proba(X_tr), threshold)}

    importance = {}
    if hasattr(est, "feature_importances_"):
        importance = dict(sorted(zip(names, map(float, est.feature_importances_)), key=lambda kv: -kv[1])[:25])
    created = datetime.now(timezone.utc)
    bundle.metadata = {
        "model_version": f"{algorithm}-{created:%Y%m%dT%H%M%SZ}", "algorithm": algorithm, "created_at": created.isoformat(),
        "library_versions": lib_versions(), "feature_names": names, "dropped_features": dropped, "threshold": threshold,
        "params": params, "seed": seed,
        "dataset": {**report.to_dict(), "warning": SYNTHETIC_WARNING if report.synthetic else None},
        "split": {"test_size": test_size, "group_by_domain": group_by_domain, "n_train": int(len(tr)), "n_test": int(len(te))},
        "metrics": metrics, "feature_importance": importance, "feature_medians": median_baseline(X_tr),
    }
    out = bundle.save(output_dir)
    (out / "metrics.json").write_text(json.dumps({"dataset_synthetic": report.synthetic, "warning": SYNTHETIC_WARNING if report.synthetic else None, **metrics}, indent=2))

    t = metrics["test"]
    log(f"\nTEST SET ({t['n_samples']} URLs, threshold {threshold}):")
    for k in ("accuracy", "precision", "recall", "f1", "roc_auc", "brier_score"):
        log(f"  {k:<11} {t[k]:.4f}")
    cm = t["confusion_matrix"]
    log(f"  confusion matrix  (rows=actual, cols=predicted)\n              legit  phish\n    legit   {cm['tn']:>6} {cm['fp']:>6}\n    phish   {cm['fn']:>6} {cm['tp']:>6}")
    log(f"Saved model '{bundle.version}' to {out}")
    return bundle.metadata


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", required=True, help="CSV with columns url,label (+ optional security columns). See data/README.md")
    ap.add_argument("--output-dir", default="models")
    ap.add_argument("--algorithm", choices=ALGORITHMS, default="xgboost")
    ap.add_argument("--test-size", type=float, default=0.2)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--threshold", type=float, default=0.5, help="decision threshold for 'phishing'")
    ap.add_argument("--no-group-split", action="store_true", help="plain stratified split (can leak near-duplicate domains across train/test)")
    a = ap.parse_args(argv)
    try:
        run(a.data, a.output_dir, a.algorithm, a.test_size, a.seed, a.threshold, not a.no_group_split)
    except (ValueError, FileNotFoundError, RuntimeError) as e:
        print(f"Training failed: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
